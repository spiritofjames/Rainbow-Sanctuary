import { copyFileSync, existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const publicFiles = new Set([
  "favicon.svg", "site.webmanifest", "knowledge-index.json", "knowledge-feed.xml",
  "robots.txt", "sitemap.xml", "llms.txt", "llms-full.txt"
]);
const browserFiles = new Set([
  "application.css", "events-calendar.css", "group-journey.css", "knowledge.css",
  "offer-experience.css", "persona-faqs.css", "retreat-event.css", "site.css", "supported-pathways.css",
  "cta-effects.js", "donation-selector.js", "events-calendar.js", "group-healing-scheduler.js",
  "home-hero-video.js", "image-slot.js", "kids-weekly-practice-checkout.js", "knowledge-search.js",
  "offer-experience.js", "payment-confirmation.js", "persona-faqs.js", "public-event-feed.js",
  "regeneration-maintenance-checkout.js", "regeneration-maintenance-scheduler.js", "retreat-audio.js",
  "retreat-gallery.js", "retreat-integration-slider.js", "retreat-story-song.js",
  "retreat-testimonial-videos.js", "retreat-video.js", "site-config.js", "support.js", "supported-pathway-scheduler.js"
]);
const componentFiles = ["SiteNav.dc.html", "SiteNavCinematic.dc.html", "SiteNavFixed.dc.html", "SiteNavLotus.dc.html"];
const publicDirectories = ["assets", "pagefind", "markdown"];
const interfaceFiles = ["guardian/index.html", "guardian/config.yml", "guardian/sveltia-cms.js", "review/index.html"];
const marker = ".rainbow-generated-output";
const markerText = "Generated by scripts/build-public-site.mjs\n";

// Vercel serves only this directory statically. api/ and its email imports stay
// in the source checkout for function tracing, never in the public file tree.
export function buildPublicSite(source = root) {
  const config = JSON.parse(readFileSync(path.join(source, "vercel.json"), "utf8"));
  const pageFiles = new Set([...componentFiles, ...config.rewrites
    .map(rule => rule.destination).filter(destination => /^\/[\w-]+\.dc\.html$/.test(destination))
    .map(destination => destination.slice(1))]);
  const output = path.join(source, "public-build");
  if (existsSync(output)) {
    if (lstatSync(output).isSymbolicLink() || !existsSync(path.join(output, marker)) ||
        readFileSync(path.join(output, marker), "utf8") !== markerText) {
      throw new Error("Refusing to replace unrecognized public-build directory");
    }
    rmSync(output, { recursive: true });
  }
  mkdirSync(output);
  writeFileSync(path.join(output, marker), markerText);
  const copied = [];
  const copy = (relative) => {
    const from = path.join(source, relative);
    const stat = lstatSync(from);
    if (stat.isSymbolicLink()) throw new Error(`Public output cannot contain symlinks: ${relative}`);
    if (stat.isDirectory()) {
      for (const entry of readdirSync(from).sort()) {
        if (!entry.startsWith(".")) copy(path.join(relative, entry));
      }
      return;
    }
    mkdirSync(path.dirname(path.join(output, relative)), { recursive: true });
    copyFileSync(from, path.join(output, relative));
    copied.push(relative);
  };
  for (const name of readdirSync(source).sort()) {
    if (publicFiles.has(name) || pageFiles.has(name) || browserFiles.has(name)) copy(name);
  }
  for (const directory of publicDirectories) copy(directory);
  for (const file of interfaceFiles) if (existsSync(path.join(source, file))) copy(file);
  return { output, files: copied };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = buildPublicSite();
  console.log(`Public static output: ${result.files.length} files in public-build; source and server files excluded.`);
}
